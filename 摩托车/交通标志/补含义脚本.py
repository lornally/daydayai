def note_for(label):
    if label in NOTE:
        return NOTE[label]
    base = re.sub(r'\d+$', '', label)
    if base in NOTE:
        return NOTE[base]
    for k, v in sorted(NOTE.items(), key=lambda x: -len(x[0])):
        if k in label:
            return v
    return None


s = open(HTML, encoding="utf-8").read()
