hits = 0


def repl(m):
    global hits
    label = html.unescape(m.group(1))
    n = note_for(label)
    if not n:
        return m.group(0)
    hits += 1
    return "<figcaption>%s<em>%s</em></figcaption>" % (html.escape(label), html.escape(n))


s = re.sub(r"<figcaption>(.*?)</figcaption>", repl, s)
open(HTML, "w", encoding="utf-8").write(s)
